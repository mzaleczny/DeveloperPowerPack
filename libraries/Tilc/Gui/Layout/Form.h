            void RefreshList(Tilc::Gui::TMultiColumnListbox* lb, Tilc::TExtString ItemsJson)
            {
                lbList->DeleteItems();
                lbList->SetColumnWidths(lbListColumnsWidths);
                lbList->SetHeaderCaptions(lbListColumnsCaptions);

                Tilc::TJsonParser JsonParser;
                Tilc::TStdObject* JsonRoot = JsonParser.parse(ItemsJson);
                if (JsonRoot)
                {
                    for (auto* ItemObject : *JsonRoot->getAsObject("root")->getAsArray("items"))
                    {
                        Tilc::TStdObject* o = ItemObject->oValue;
                        if (o)
                        {
                            TItemType Item;
                            Item.FromJsonObject(o);
                            auto* lbItem = lb->AddItem(Item.GetDataForListColumns());
                            if (lbItem)
                            {
                                lbItem->m_Props["id"] = Item.id;
                                lbItem->m_Props["IndexInChangedList"] = "-1";
                            }
                        }
                    }
                    delete JsonRoot;
                }
            }

            void AddCategoriesCheckboxes(Tilc::Gui::TStyledWindow* wnd, Tilc::TExtString ItemsJson)
            {
                Tilc::TJsonParser JsonParser;
                Tilc::TStdObject* JsonRoot = JsonParser.parse(ItemsJson);
                constexpr int const padding = 10.0f;
                SDL_FRect Position = {padding, padding, 200.0f, 25.0f};
                float y = padding;
                if (JsonRoot)
                {
                    constexpr int const ColumnsCount = 4;
                    size_t CategoriesCount = JsonRoot->getAsObject("root")->getAsArray("items")->size();
                    size_t CategoriesPerColumn = CategoriesCount / ColumnsCount + 1;
                    int Column = 0;
                    for (size_t i = 0; i < CategoriesCount; ++i)
                    {
                        Position.x = padding + Column * (200.0f + 50.0f);
                        Position.y = padding;
                        for (size_t j = 0; j < CategoriesPerColumn && i < CategoriesCount; ++j, ++i)
                        {
                            Tilc::TStdObjectProperty* ItemObject = (*JsonRoot->getAsObject("root")->getAsArray("items"))[i];
                            Tilc::TStdObject* o = ItemObject->oValue;
                            if (o)
                            {
                                TItemType Item;
                                Item.FromJsonObject(o);

                                Tilc::Gui::TCheckbox* Checkbox = new Tilc::Gui::TCheckbox(wnd, "Cat_" + Item.id, Position,
                                        Item.name, false);
                                if (Checkbox)
                                {
                                    Checkbox->m_Props["id"] = Item.id;
                                }
                                Position.y += 30.0f;
                                if (Position.y > y)
                                {
                                    y = Position.y;
                                }
                            }
                        }
                        --i;
                        ++Column;
                    }
                    delete JsonRoot;
                }

                Position.x = padding;
                Position.y = y;
                Position.w = 150.0f;
                Tilc::Gui::TGuiControl* btnSave = new Tilc::Gui::TButton(wnd, "SaveButton", Position, "Zapisz kategorie");
                //btnSave->OnClick = &TFormPackage::OnEditOkClick;
                Position.x += Position.w + 10.0f;
                Tilc::Gui::TGuiControl* btnCancel = new Tilc::Gui::TButton(wnd, "CancelButton", Position, "Anuluj");
                btnCancel->OnClick = &TFormPackage::OnSetCategoriesCancelClick;
            }

            void LoadMiniatures(Tilc::TExtString MiniaturesServerNames)
            {
                //std::cout << "LoadMiniatures: " << MiniaturesServerNames << std::endl;
                auto lstImageListView = dynamic_cast<Tilc::Gui::TImageListView*>(WndEditForm->GetChild("lstImageList_ProductPictures"));
                if (lstImageListView)
                {
                    std::vector<Tilc::TExtString> Miniatures;
                    Tilc::TExtString MiniatureBlob;

                    lstImageListView->RemoveAllImages();
                    MiniaturesServerNames.Explode(',', Miniatures);

                    //int i = 0;
                    for (auto const &m : Miniatures)
                    {
                        //std::cout << "Find for server name: " << m << std::endl;
                        if (auto p1 = m_CachedMiniaturesMap.find(m); p1 != m_CachedMiniaturesMap.end())
                        {
                            //std::cout << "Find for client name: " << p1->second << std::endl;
                            if (auto p2 = m_CachedMiniatures.find(p1->second); p2 != m_CachedMiniatures.end())
                            {
                                //std::cout << "Dodaję " << ++i << std::endl;
                                lstImageListView->AddImage(p2->second, m);
                            }
                        }
                    }
                }
            }

