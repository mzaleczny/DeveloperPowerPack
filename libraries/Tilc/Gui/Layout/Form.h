            int SynchronizeError{};
            int Synchronize(const Tilc::TExtString& LoggedUser)
            {
                SynchronizeError = 0;
                if (lbList)
                {
                    // Tutaj usuwamy puste pozycje z listy pozycji zmienionych, bo nie chcemy ich zapisać w bazie oraz konieczność poprawności mapowania indeksów
                    // nie jest juz konieczna ze względu na to, ze po zapisie lista pozycji jest pobierana na nowo i wektory zmian są zerowane. Czyli stan formularza
                    // zostaje zresetowany do stanu początkowego z uaktualnioną listą
                    std::erase_if(m_ChangedItems, [](auto x) {
                        return x.IsEmpty();
                    });

                    Tilc::TExtString ItemsJson;
                    bool DoRefreshAfterUpdate = m_ItemsToDelete.size() > 0;

                    if (m_ItemsToDelete.size() > 0)
                    {
#ifdef __EMSCRIPTEN__
                        Tilc::Apps::Www::Delete(Url_Delete, m_ItemsToDelete, [this, DoRefreshAfterUpdate](Tilc::TExtString ItemsJson)
                        {
                            if (ItemsJson.find("Not Logged In") != std::string::npos)
                            {
                                SynchronizeError = 1;
                            }
                            else
                            {
                                m_ItemsToDelete.clear();
                                if (!DoRefreshAfterUpdate && !ItemsJson.empty())
                                {
                                    TFormPackage::RefreshList(lbList, ItemsJson);
                                }
                            }
                        }, LoggedUser);
#else
                        ItemsJson = Tilc::Apps::Www::Delete(Url_Delete, m_ItemsToDelete, LoggedUser);
                        if (ItemsJson.find("Not Logged In") != std::string::npos)
                        {
                            SynchronizeError = 1;
                        }
                        else
                        {
                            m_ItemsToDelete.clear();
                            if (!DoRefreshAfterUpdate && !ItemsJson.empty())
                            {
                                TFormPackage::RefreshList(lbList, ItemsJson);
                            }
                        }
#endif
                    }

                    if (SynchronizeError != 0) return SynchronizeError;

                    if (m_ChangedItems.size() > 0)
                    {
#ifdef __EMSCRIPTEN__
                        Tilc::Apps::Www::Save(Url_Save, m_ChangedItems, [this, DoRefreshAfterUpdate](Tilc::TExtString ItemsJson) {
                            if (ItemsJson.find("Not Logged In") != std::string::npos)
                            {
                                SynchronizeError = 2;
                            }
                            else
                            {
                                m_ChangedItems.clear();
                                if (!DoRefreshAfterUpdate && !ItemsJson.empty())
                                {
                                    TFormPackage::RefreshList(lbList, ItemsJson);
                                }
                            }
                        }, LoggedUser);
#else
                        ItemsJson = Tilc::Apps::Www::Save<TItemType>(Url_Save, m_ChangedItems, LoggedUser);
                        if (ItemsJson.find("Not Logged In") != std::string::npos)
                        {
                            SynchronizeError = 2;
                        }
                        else
                        {
                            m_ChangedItems.clear();
                            if (!ItemsJson.empty())
                            {
                                TFormPackage::RefreshList(lbList, ItemsJson);
                            }
                        }
#endif
                    }

                    if (SynchronizeError != 0) return SynchronizeError;
                }
                return 0;
            }

            static void ShowEditWindow(TFormPackage* Pack, TItemType Item, int Index = -1)
            {
                Tilc::Gui::TStyledWindow* EditWindow = Pack->WndEditForm;
                if (EditWindow)
                {
                    auto* FormPackage = reinterpret_cast<Tilc::Gui::TFormPackage<TItemType>*>(GetPointer(EditWindow, "FormPackage"));
                    if (FormPackage)
                    {
                        if (FormPackage->HideAllWindowsFromParent)
                        {
                            FormPackage->HideAllWindowsFromParent();
                        }
                    }

                    EditWindow->Show();
                    EditWindow->Focus();
                    EditWindow->m_Props["IndexInChangedList"] = std::to_string(Index);
                    Tilc::TExtString Caption, Pictures;
                    if (Item.IsEmpty())
                    {
                        Caption = Item.AddLabel;
                    }
                    else
                    {
                        Caption = Item.EditLabel;
                        // add all pictures assigned to item already
                        std::for_each(Item.pictures.begin(), Item.pictures.end(), [&Pictures](const Tilc::TExtString& Pic)
                        {
                            if (!Pictures.empty())
                            {
                                Pictures += ",";
                            }
                            Pictures += Pic;
                        });
                    }
                    // add all temporary pictures assigned to item during edit but before synchro and saving them to db
                    std::for_each(Item.new_pictures.begin(), Item.new_pictures.end(), [&Pictures](const Tilc::TExtString& Pic)
                    {
                        if (!Pictures.empty())
                        {
                            Pictures += ",";
                        }
                        Pictures += Pic;
                    });
                    // Save added pictures in props
                    EditWindow->m_Props["Pictures"] = Pictures;
                    auto lstImageListView = dynamic_cast<Tilc::Gui::TImageListView*>(EditWindow->GetChild("lstImageList_ProductPictures"));
                    if (lstImageListView)
                    {
                        lstImageListView->RemoveAllImages();
                        if (!Pictures.empty())
                        {
                            FormPackage->LoadMiniatures(Pictures);
                        }
                    }

                    EditWindow->SetChildrenTextes(Item.GetDataMap());
                    if (FormPackage)
                    {
                        FormPackage->lblTitle->SetText(Caption);
                        // domyślnie na start czyścimy liste zcachowanych oryginalnych obrazków, żeby zwolnić pamięć. Obrazki do tego cache będą dodawane
                        // podczas uploadu nowych zdjęć lub podczas kliknięcia w istniejące zdjęcie po to żeby je pwiększyć (w tym przypadku jest ono pobierane
                        // oddzielnym fetchem z serwera)
                        std::for_each(FormPackage->m_CachedOriginalPictures.begin(), FormPackage->m_CachedOriginalPictures.end(), [](auto& PicPair)
                        {
                            if (PicPair.second) SDL_DestroyTexture(PicPair.second);
                        });
                        FormPackage->m_CachedOriginalPictures.clear();
                    }
                }
            }

